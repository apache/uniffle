set -o errexit
set -o nounset
set -o pipefail

SCRIPT_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
MODULE="github.com/apache/incubator-uniffle/deploy/kubernetes/operator"

# kube_codegen.sh installs the generators into $GOBIN; keep them in local/ with
# the other tools the Makefile downloads.
export GOBIN="${SCRIPT_ROOT}/local"

cd "${SCRIPT_ROOT}"
go mod download k8s.io/code-generator
CODEGEN_PKG="$(go list -m -f '{{.Dir}}' k8s.io/code-generator)"
source "${CODEGEN_PKG}/kube_codegen.sh"

# DeepCopy methods are generated by controller-gen (make generate), so only the
# clientset, listers and informers are generated here.
kube::codegen::gen_client \
  --with-watch \
  --output-dir "${SCRIPT_ROOT}/pkg/generated" \
  --output-pkg "${MODULE}/pkg/generated" \
  --boilerplate "${SCRIPT_ROOT}/hack/headers/header.go.txt" \
  "${SCRIPT_ROOT}/api"
